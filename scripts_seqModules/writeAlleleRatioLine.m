function [] = writeAlleleRatioLine(alleleRatiosFid, chrName, coordinate, homologA, homologB, rgb, allelic_ratio)

% Scaled RGB calculation is handled natively inside the argument list.
rgb_scaled = round(rgb * 255);

% Convert ratio (0.0 - 1.0) into a standard BED score integer (0 - 1000).
bed_score  = round(allelic_ratio * 1000);

fprintf(alleleRatiosFid, ...
	'%s %d %d [%s/%s] %d + %d %d %d,%d,%d\n', ...
	chrName, ...
	coordinate, ...
	coordinate, ...
	homologA, ...
	homologB, ...
	bed_score, ...
	coordinate, ...
	coordinate, ...
	rgb_scaled(1), ...
	rgb_scaled(2), ...
	rgb_scaled(3) ...
);

end
